// Registry of every content type managed by the generic admin CMS.

export type ColumnDef = {
  field: string;
  label: string;
  type?: "text" | "badge" | "date" | "datetime" | "boolean" | "image" | "status" | "count";
  labels?: Record<string, string>;
  className?: string;
};

export type ResourceConfig = {
  key: string;
  model: string;
  label: string;
  singular: string;
  description: string;
  titleField: string;
  subtitleField?: string;
  fields: FieldDef[];
  columns: ColumnDef[];
  searchFields: string[];
  orderBy: Record<string, "asc" | "desc">[];
  orderable?: boolean;
  /** Field + values used for draft/publish. */
  status?: { field: string; published: string; draft: string; options: Option[] };
  /** Filter tabs (e.g. sections by page). */
  groupBy?: { field: string; options: Option[] };
  tags: CacheTag[];
  include?: Record<string, unknown>;
  canCreate?: boolean;
  canDelete?: boolean;
  publicPath?: (r: Record<string, unknown>) => string | null;
  previewable?: boolean;
  defaults?: Record<string, unknown>;
  /** Fields that need a unique value across the table. */
  unique?: string[];
};

const opts = <T extends string>(values: readonly T[], labels?: Record<string, string>): Option[] =>
  values.map((v) => ({ value: v, label: labels?.[v] ?? v }));

